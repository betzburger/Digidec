    /// Zeichensatz 0 = EBU Latin, 4 = UCS-2 (big endian), 15 = UTF-8; unbekannte Zeichensätze als EBU Latin
    public static func decode(_ bytes: [UInt8], charset: Int) -> String {
        switch charset {
        case 15:
            return String(decoding: bytes, as: UTF8.self)
        case 6:
            var units = [UInt16]()
            var i = 0
            while i + 1 < bytes.count { units.append(UInt16(bytes[i]) << 8 | UInt16(bytes[i + 1])); i += 2 }
            return String(decoding: units, as: UTF16.self)
        default:
            return String(utf16CodeUnits: bytes.map { ebuLatin[Int($0)] }, count: bytes.count)
        }
    }
